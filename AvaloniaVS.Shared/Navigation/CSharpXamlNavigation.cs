    /// <summary>
    /// What a C# symbol has to do with an Avalonia XAML file: an <c>x:Name</c> field generated from
    /// it, or an event handler it references. Detected synchronously from cheap facts (declaration
    /// paths and the XAML text), so a command filter can decide whether to take a command.
    /// </summary>
    internal sealed class XamlBackedSymbol
    {
        public enum SymbolKind
        {
            /// <summary>A field generated by Avalonia's name generator for <c>x:Name</c>.</summary>
            NamedElement,

            /// <summary>A code-behind method used as an event handler in the XAML.</summary>
            EventHandler,
        }

        public SymbolKind Kind { get; private set; }

        public ISymbol Symbol { get; private set; }

        public string XamlPath { get; private set; }

        public string XamlText { get; private set; }

        public XamlDocument Document { get; private set; }

        /// <summary>The solution snapshot <see cref="Symbol"/> was resolved from.</summary>
        public Solution Solution { get; set; }

        /// <summary>The identifier's span in the C# buffer it was found in.</summary>
        public Span Span { get; set; }

        public static XamlBackedSymbol TryCreate(ISymbol symbol)
        {
            if (symbol?.ContainingType is not { } type)
            {
                return null;
            }

            if (symbol is IFieldSymbol or IPropertySymbol &&
                symbol.Locations.Where(l => l.IsInSource).All(l => XamlRoslynContext.IsGenerated(l.SourceTree?.FilePath)) &&
                FindXaml(type) is { } named &&
                named.Document.Elements.Any(e => e.ElementName == symbol.Name))
            {
                named.Kind = SymbolKind.NamedElement;
                named.Symbol = symbol;
                return named;
            }

            if (symbol is IMethodSymbol { MethodKind: MethodKind.Ordinary, IsStatic: false, ReturnsVoid: true } &&
                FindXaml(type) is { } handler &&
                handler.Document.Elements.Any(e => e.Attributes.Any(a => a.Value.Trim() == symbol.Name && !a.Name.StartsWith("xmlns", StringComparison.Ordinal))))
            {
                handler.Kind = SymbolKind.EventHandler;
                handler.Symbol = symbol;
                return handler;
            }

            return null;
        }

        /// <summary>
        /// The XAML whose <c>x:Class</c> is <paramref name="type"/>: the <c>Foo.axaml</c> next to a
        /// <c>Foo.axaml.cs</c> partial (the Avalonia convention), confirmed by its <c>x:Class</c>.
        /// </summary>
        private static XamlBackedSymbol FindXaml(INamedTypeSymbol type)
        {
            var fullName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", "");

            foreach (var reference in type.DeclaringSyntaxReferences)
            {
                var path = reference.SyntaxTree.FilePath ?? "";
                if (!path.EndsWith(".axaml.cs", StringComparison.OrdinalIgnoreCase) &&
                    !path.EndsWith(".xaml.cs", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                var xamlPath = path.Substring(0, path.Length - ".cs".Length);
                if (!File.Exists(xamlPath))
                {
                    continue;
                }

                string text;
                try
                {
                    text = File.ReadAllText(xamlPath);
                }
                catch (IOException)
                {
                    continue;
                }

                var document = XamlDocument.Parse(text);
                if (document.Root?.GetXamlDirective("Class")?.Value?.Trim() == fullName)
                {
                    return new XamlBackedSymbol { XamlPath = xamlPath, XamlText = text, Document = document };
                }
            }

            return null;
        }
    }

    [Export(typeof(IVsTextViewCreationListener))]
    [Name("Avalonia C# to XAML navigation")]
    [ContentType("CSharp")]
    [TextViewRole(PredefinedTextViewRoles.Document)]
    internal sealed class CSharpXamlNavigationListener : IVsTextViewCreationListener
    {
        [Import]
        internal IVsEditorAdaptersFactoryService AdapterService { get; set; }

        public void VsTextViewCreated(IVsTextView textViewAdapter)
        {
            try
            {
                var view = AdapterService.GetWpfTextView(textViewAdapter);
                if (view != null)
                {
                    view.Properties.GetOrCreateSingletonProperty(() => new CSharpXamlNavigationCommandHandler(view, textViewAdapter));
                }
            }
            catch (Exception ex)
            {
                // Never break the C# editor over an optional feature.
                Log.Logger.Debug(ex, "Couldn't set up C# to XAML navigation");
            }
        }
    }

    /// <summary>
    /// In C#: F12 on an <c>x:Name</c> field goes to the element in the XAML instead of Avalonia's
    /// generated code, and Shift+F12 on such a field or on an event handler also lists the XAML
    /// usages. Every other symbol is left to Roslyn.
    /// </summary>
    internal sealed class CSharpXamlNavigationCommandHandler : IOleCommandTarget
    {
        private readonly ITextView _view;
        private readonly IOleCommandTarget _next;

        public CSharpXamlNavigationCommandHandler(ITextView view, IVsTextView textViewAdapter)
        {
            _view = view;
            textViewAdapter.AddCommandFilter(this, out _next);
        }

        public int QueryStatus(ref Guid pguidCmdGroup, uint cCmds, OLECMD[] prgCmds, IntPtr pCmdText) =>
            _next.QueryStatus(ref pguidCmdGroup, cCmds, prgCmds, pCmdText);

        public int Exec(ref Guid pguidCmdGroup, uint nCmdID, uint nCmdexecopt, IntPtr pvaIn, IntPtr pvaOut)
        {
            ThreadHelper.ThrowIfNotOnUIThread();

            if (pguidCmdGroup == VSConstants.GUID_VSStandardCommandSet97 &&
                (nCmdID == (uint)VSConstants.VSStd97CmdID.GotoDefn || nCmdID == (uint)VSConstants.VSStd97CmdID.FindReferences))
            {
                var findReferences = nCmdID == (uint)VSConstants.VSStd97CmdID.FindReferences;

                try
                {
                    var backed = GetXamlBackedSymbol(_view);

                    // F12 on a handler method is just a C# method: leave it to Roslyn.
                    if (backed != null && (findReferences || backed.Kind == XamlBackedSymbol.SymbolKind.NamedElement))
                    {
                        AvaloniaVS.Services.BackgroundWork.Start(
                            () => findReferences ? FindReferencesAsync(backed) : GoToXamlAsync(backed),
                            findReferences ? "AvaloniaVS/CSharpFindXamlReferences" : "AvaloniaVS/CSharpGoToXaml");
                        return VSConstants.S_OK;
                    }
                }
                catch (Exception ex)
                {
                    Log.Logger.Debug(ex, "C# to XAML navigation check failed; leaving the command to Roslyn");
                }
            }

            return _next.Exec(ref pguidCmdGroup, nCmdID, nCmdexecopt, pvaIn, pvaOut);
        }

        /// <summary>The XAML-backed symbol at <paramref name="view"/>'s caret, or null.</summary>
        internal static XamlBackedSymbol GetXamlBackedSymbol(ITextView view)
        {
            var position = view.Caret.Position.BufferPosition.Position;

            // F12 is user-initiated, so briefly waiting for the (normally cached) semantic model is fine.
            return ThreadHelper.JoinableTaskFactory.Run(
                () => GetXamlBackedSymbolAsync(view.TextBuffer, position, CancellationToken.None));
        }

        /// <summary>
        /// The XAML-backed symbol at <paramref name="position"/> in a C# buffer, or null. Also sets
        /// <see cref="XamlBackedSymbol.Span"/> to the identifier's span.
        /// </summary>
        internal static async Task<XamlBackedSymbol> GetXamlBackedSymbolAsync(ITextBuffer buffer, int position, CancellationToken cancellationToken)
        {
            var path = XamlRoslynContext.GetFilePath(buffer);
            if (path is null ||
                Package.GetGlobalService(typeof(Microsoft.VisualStudio.ComponentModelHost.SComponentModel)) is not Microsoft.VisualStudio.ComponentModelHost.IComponentModel componentModel)
            {
                return null;
            }

            var workspace = componentModel.GetService<VisualStudioWorkspace>();
            var documentId = workspace.CurrentSolution.GetDocumentIdsWithFilePath(path).FirstOrDefault();
            var document = documentId is null ? null : workspace.CurrentSolution.GetDocument(documentId);
            if (document is null)
            {
                return null;
            }

            var model = await document.GetSemanticModelAsync(cancellationToken).ConfigureAwait(false);
            if (model is null)
            {
                return null;
            }

            var symbol = await SymbolFinder.FindSymbolAtPositionAsync(model, position, workspace, cancellationToken).ConfigureAwait(false);
            var backed = XamlBackedSymbol.TryCreate(symbol);
            if (backed != null)
            {
                backed.Solution = document.Project.Solution;
                var token = (await model.SyntaxTree.GetRootAsync(cancellationToken).ConfigureAwait(false)).FindToken(position);
                backed.Span = new Span(token.Span.Start, token.Span.Length);
            }

            return backed;
        }

        internal static async Task GoToXamlAsync(XamlBackedSymbol backed)
        {
            var element = backed.Document.Elements.FirstOrDefault(e => e.ElementName == backed.Symbol.Name);
            var attribute = element?.GetXamlDirective("Name") ?? element?.GetAttribute("Name");
            if (attribute is null || !await NavigationHelper.OpenAtAsync(backed.XamlPath, attribute.ValueStart))
            {
                await NavigationHelper.SetStatusAsync($"Couldn't open '{backed.Symbol.Name}' in {Path.GetFileName(backed.XamlPath)}.");
            }
        }

        private static async Task FindReferencesAsync(XamlBackedSymbol backed)
        {
            await NavigationHelper.SetStatusAsync($"Finding references to '{backed.Symbol.Name}'…");

            var results = new List<XamlSourceLocation>();
            var kind = backed.Kind == XamlBackedSymbol.SymbolKind.NamedElement ? XamlNavigationKind.XName : XamlNavigationKind.EventHandler;

            // XAML usages (and, for x:Name, the declaring element).
            results.AddRange(await XamlLocationService.FindXamlUsagesAsync(
                backed.XamlPath, backed.XamlText, kind, backed.Symbol.Name, null, CancellationToken.None));

            // C#: the hand-written declaration (a handler method; x:Name fields have none) and uses.
            var context = await XamlRoslynContext.CreateAsync(backed.XamlPath, CancellationToken.None);
            if (context != null)
            {
                results.AddRange(XamlLocationService.SourceDefinitions(context, handWrittenOnly: true, backed.Symbol));
            }

            results.AddRange(await XamlLocationService.FindCSharpReferencesAsync(backed.Solution, backed.Symbol, CancellationToken.None));

            var locations = XamlLocationService.Normalize(results);
            await ReferencesWindow.ShowAsync($"'{backed.Symbol.Name}' references", locations);
            await NavigationHelper.SetStatusAsync($"{locations.Count} result(s) for '{backed.Symbol.Name}'.");
        }
    }

    /// <summary>
    /// Ctrl+Click (and other modern Go To Definition requests) in C#. The editor sends Ctrl+Click as
    /// a <see cref="Microsoft.VisualStudio.Text.Editor.Commanding.Commands.GoToDefinitionCommandArgs"/>
    /// straight to Roslyn's handler, bypassing the legacy command filter that handles F12, so this
    /// runs first for XAML-backed <c>x:Name</c> fields and passes on everything else.
    /// </summary>
    [Export(typeof(Microsoft.VisualStudio.Commanding.ICommandHandler))]
    [ContentType("CSharp")]
    [Name("Avalonia C# go to XAML definition")]
    [Order(Before = "Go To Definition Command Handler")]
    internal sealed class CSharpXamlGoToDefinitionCommandHandler
        : Microsoft.VisualStudio.Commanding.ICommandHandler<Microsoft.VisualStudio.Text.Editor.Commanding.Commands.GoToDefinitionCommandArgs>
    {
        public string DisplayName => "Avalonia: go to XAML definition";

        public Microsoft.VisualStudio.Commanding.CommandState GetCommandState(
            Microsoft.VisualStudio.Text.Editor.Commanding.Commands.GoToDefinitionCommandArgs args) =>
            Microsoft.VisualStudio.Commanding.CommandState.Unspecified;

        public bool ExecuteCommand(
            Microsoft.VisualStudio.Text.Editor.Commanding.Commands.GoToDefinitionCommandArgs args,
            Microsoft.VisualStudio.Commanding.CommandExecutionContext executionContext)
        {
            try
            {
                var backed = CSharpXamlNavigationCommandHandler.GetXamlBackedSymbol(args.TextView);
                if (backed?.Kind != XamlBackedSymbol.SymbolKind.NamedElement)
                {
                    return false;
                }

                AvaloniaVS.Services.BackgroundWork.Start(
                    () => CSharpXamlNavigationCommandHandler.GoToXamlAsync(backed),
                    "AvaloniaVS/CSharpGoToXaml");
                return true;
            }
            catch (Exception ex)
            {
                Log.Logger.Debug(ex, "C# go to XAML check failed; leaving it to Roslyn");
                return false;
            }
        }
    }
